def unit(value: str) -> dict:
    return {"stringUnit": {"state": "translated", "value": value}}


def catalog(strings: dict) -> str:
    return json.dumps({"sourceLanguage": "en", "strings": strings, "version": "1.0"},
                      ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def main() -> None:
    build = pathlib.Path(sys.argv[1])
    keys = set()
    for path in build.glob("Objects-normal/*/*.stringsdata"):
        for table, entries in json.loads(path.read_text()).get("tables", {}).items():
            if table == "Localizable":
                keys.update(entry["key"] for entry in entries)
    if not keys:
        sys.exit(f"no extracted strings under {build} — build with SWIFT_EMIT_LOC_STRINGS first")

    missing = sorted(keys - ZH.keys())
    stale = sorted(ZH.keys() - keys)
    if missing or stale:
        for key in missing:
            print(f"missing translation: {key!r}")
        for key in stale:
            print(f"translation without a key: {key!r}")
        sys.exit(1)

    (HERE / "Rendu/Localizable.xcstrings").write_text(catalog({
        key: {"localizations": {"zh-Hans": unit(ZH[key])}} for key in sorted(keys)
    }))
    (HERE / "Rendu/InfoPlist.xcstrings").write_text(catalog({
        key: {"localizations": {"en": unit(en), "zh-Hans": unit(zh)}} for key, (en, zh) in INFO_PLIST.items()
    }))
    print(f"Localizable.xcstrings: {len(keys)} keys; InfoPlist.xcstrings: {len(INFO_PLIST)} keys")


if __name__ == "__main__":
    main()
